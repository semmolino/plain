-- ── Bestandskorrektur: doppelte Honorarzonen ──────────────────────────────
-- Die Technische Ausrüstung (FEE_MASTER_ID 14) hatte I/II/III doppelt
-- (IDs 55, 56, 57) — im Zonen-Dropdown erschien jede Zone zweimal.
-- Nur löschen, was keine Berechnung referenziert; sonst bleibt die Zeile
-- stehen und muss von Hand umgehängt werden.
DELETE FROM "FEE_ZONES" z
 WHERE z."ID" IN (55, 56, 57)
   AND NOT EXISTS (SELECT 1 FROM "FEE_CALCULATION_MASTER" m WHERE m."ZONE_ID" = z."ID")
   AND NOT EXISTS (SELECT 1 FROM "FEE_CALC_ZONE_SPLIT" s WHERE s."ZONE_ID" = z."ID");

-- Erst NACH der Bereinigung: eine Honorarzone darf es je Leistungsbild nur
-- einmal geben. Vor dem DELETE oben würde dieser Index an genau den Dubletten
-- scheitern, die er künftig verhindert.
-- Schlägt das hier fehl, hängt noch eine Berechnung an einer Dublette — dann
-- die betroffene FEE_CALCULATION_MASTER.ZONE_ID auf die Zone mit der
-- kleineren ID umhängen und die Migration erneut ausführen.
CREATE UNIQUE INDEX IF NOT EXISTS "uq_fee_zones_master_name"
  ON "FEE_ZONES" ("FEE_MASTER_ID", UPPER(TRIM("NAME_SHORT")));

