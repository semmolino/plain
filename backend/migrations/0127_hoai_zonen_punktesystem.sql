-- Migration 0127 — Honorarzonen-Punktesystem (§ 5 Abs. 2 HOAI)
--
-- Damit ist die Zonenbestimmung vollständig. Bisher gab es nur die
-- Objektliste (0120/0124) — die ist laut § 5 Abs. 2 aber nur die ergänzende
-- Hilfe ("unter Berücksichtigung der Regelbeispiele in den Objektlisten").
-- Der eigentliche Mechanismus sind die BEWERTUNGSMERKMALE: je Merkmal Punkte
-- vergeben, Summe bilden, Zone ablesen.
--
-- 15 Punktesysteme, alle maschinell aus dem amtlichen Volltext geparst:
--   § 20 Flächennutzungsplan · § 21 Bebauungsplan
--   §§ 28–32 Landschaftsplanung (5 Leistungsbilder)
--   § 35 Gebäude UND Innenräume (zwei getrennte Systeme in einem Paragraphen)
--   § 40 Freianlagen · § 44 Ingenieurbauwerke · § 48 Verkehrsanlagen
--   Anlage 1.1.2 UVS · Anlage 1.4.3 und 1.4.6 Ingenieurvermessung
--
-- DREI TEXTVARIANTEN, EIN DATENMODELL:
--   A) je Merkmal eine eigene Höchstpunktzahl ("Nummer 1, 4 bis 6 mit je bis
--      zu 6 Punkten") — die Mehrzahl der Leistungsbilder
--   B) eine gemeinsame Stufenskala für alle Merkmale ("geringe Anforderungen:
--      1 Punkt / durchschnittliche: 2 / hohe: 3") — § 20 und § 21
--   C) je Merkmal benannte Stufen mit Punktspannen ("sehr gering 1 bis 3 …
--      sehr hoch 13 bis 15") — Ingenieurvermessung
-- Alle drei laufen auf "Merkmal → Höchstpunktzahl, Summe → Zone" hinaus. Die
-- Stufenbenennungen aus B und C stehen als LEVEL_HINT am Merkmal, damit die
-- Nutzerin nicht raten muss, was z. B. 13 von 15 Punkten bedeutet.
--
-- OHNE PUNKTESYSTEM (bewusst nicht enthalten): Tragwerksplanung (§ 52), TGA
-- (§ 56), Geotechnik (Anlage 1.3), Bauakustik/Raumakustik (Anlage 1.2.4/1.2.5)
-- ordnen die Zonen über beschreibende Merkmalstexte zu, ohne Punkte — dort
-- bleibt die Objektliste aus 0120/0124 das Mittel der Wahl. Wärmeschutz
-- (Anlage 1.2.3) erbt die Zone des Gebäudes nach § 35.
--
-- § 21 hat EIGENE Bewertungsmerkmale (Abs. 3), verweist für Gewichtung und
-- Schwellen aber auf § 20 Abs. 4 und 5 — beides ist hier aufgelöst
-- eingetragen, damit die Berechnung ohne Verweisketten auskommt.
--
-- PRÜFUNGEN vor dem Erzeugen dieser Datei (alle 15 Systeme bestanden):
--   · Summe der Höchstpunktzahlen = Obergrenze der höchsten Honorarzone
--     (z. B. § 35: 6+9+9+6+6+6 = 42 = Obergrenze Zone V)
--   · Anzahl der Punktebänder = Anzahl der Honorarzonen des Leistungsbilds
