-- Migration 0123 — HOAI 2013 als zweite Honorarordnung (Altverträge)
--
-- Verträge, die vor dem 01.01.2021 geschlossen wurden, rechnen weiterhin nach
-- der HOAI-Fassung 2013 ab. Rechtlich ist das ein wesentlicher Unterschied:
-- 2013 waren die Tafelwerte **verbindliche Mindest- und Höchstsätze**
-- ("sind in der folgenden Honorartafel festgesetzt"), seit der Fassung 2021
-- nur noch unverbindliche **Orientierungswerte**. Die Zahlen selbst sind
-- gleich geblieben.
--
-- WERTGLEICHHEIT GEPRÜFT (nicht angenommen): Stichprobenvergleich gegen den
-- Volltext der Fassung 2013 auf hoai.de/hoai/volltext/hoai-2013/ über vier
-- Leistungsbild-Familien mit unterschiedlicher Bemessungsgrundlage —
--   § 35  Gebäude (anrechenbare Kosten €)      10 Zeilen, 60 Werte  identisch
--   § 52  Tragwerksplanung (€)                  5 Zeilen, 30 Werte  identisch
--   § 20  Flächennutzungsplan (Fläche ha)       8 Zeilen, 48 Werte  identisch
--   Anlage 1.2.3 Bauphysik Wärmeschutz (€)      6 Zeilen, 36 Werte  identisch
--   Anlage 1.1.2 UVS (ha) + Phasen 3/37/50/10           identisch
-- Auch die Anlage-1-Struktur ist unverändert (1.1 UVS, 1.2 Bauphysik mit
-- 1.2.1–1.2.5, 1.3 Geotechnik, 1.4 Ingenieurvermessung mit 1.4.1–1.4.9).
-- Unterschiedlich ist nur der ANLAGENTITEL: 2013 „Beratungsleistungen",
-- 2021 „Weitere Fachplanungs- und Beratungsleistungen" — rein redaktionell.
--
-- Diese Migration ist deshalb bewusst MASCHINELL aus den bereits gegen den
-- amtlichen Volltext verifizierten Migrationen 0115–0119 generiert (Skript:
-- gen_hoai2013_full.js im Session-Scratchpad) — reine ID-Umschreibung, kein
-- einziger Wert neu erfasst oder abgetippt. Verifiziert wurde anschließend,
-- dass alle 439 FEE_TABLES-Zeilen wertidentisch zur Quelle sind und die IDs
-- exakt um den Offset verschoben wurden.
--
-- ID-Schema (kollisionsfrei zu 2021 und AHO):
--   FEE_GROUPS   3      (1 = HOAI 2021, 2 = AHO, 3 = HOAI 2013)
--   FEE_MASTERS  +1000  (2021er ID + 1000  →  1001–1014, 1101–1107)
--   FEE_ZONES    +2000
--   FEE_PHASE    +2000
--   FEE_TABLES   +2000
--
-- NICHT übernommen: die AHO-Leistungsbilder (Migrationen 0121/0122) — AHO ist
-- eine eigene Schriftenreihe, keine HOAI-Fassung, und kennt keine 2013er
-- Variante in diesem Sinn.
--
-- OFFEN (bewusst nicht Teil dieser Migration): die Vorbelegung der
-- Honorarordnung nach Vertragsdatum (Verträge vor 2021 → HOAI 2013). Aktuell
-- wählt die Nutzerin die Honorarordnung im Wizard weiterhin selbst; eine
-- automatische Vorauswahl anhand des Vertragsdatums wäre der nächste Schritt.
--
-- Voraussetzung: 0115–0119 (Quelle der Werte), 0120 (SORT_ORDER-Spalte auf
-- FEE_PHASE — wird hier für die Geotechnik-Teilleistungen mitgeschrieben).
-- Manuell im Supabase SQL-Editor ausführen (als ganzes Skript).

